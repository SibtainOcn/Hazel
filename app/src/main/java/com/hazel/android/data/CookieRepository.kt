package com.hazel.android.data

import android.content.Context
import androidx.datastore.preferences.core.booleanPreferencesKey
import androidx.datastore.preferences.core.edit
import androidx.datastore.preferences.core.stringPreferencesKey
import com.hazel.android.download.InfoCache
import com.hazel.android.download.SiteAccess
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.flow.map
import kotlinx.coroutines.withContext
import org.json.JSONArray
import org.json.JSONObject
import java.io.File

/**
 * One saved cookie set, covering a single site.
 *
 * [content] is Netscape cookie file text, which is the format yt-dlp reads. An entry can be
 * switched off without deleting it, in which case it is left out of the file handed to
 * yt-dlp but stays in the list.
 */
data class CookieEntry(
    val id: Long,
    val url: String,
    val title: String,
    val content: String,
    val enabled: Boolean = true
) {
    /** First few lines of the cookie text, for the row summary. */
    fun preview(lines: Int = 3): String =
        content.lineSequence().take(lines).joinToString("\n").take(300)
}

/**
 * Stores the user's cookie sets and keeps the file yt-dlp reads in step with them.
 *
 * Cookies let yt-dlp reach content the site will only serve to a signed-in viewer:
 * age-restricted videos, members-only posts, and anything behind a login wall. They are
 * kept in the app's private storage and are never sent anywhere except to yt-dlp.
 *
 * The list is held as JSON in the same preference store as the rest of the settings, which
 * avoids adding a database for what is normally a handful of entries.
 */
object CookieRepository {

    private val USE_COOKIES_KEY = booleanPreferencesKey("use_cookies")
    private val COOKIES_KEY = stringPreferencesKey("cookie_entries")

    /**
     * The browser identity the last sign-in was made under.
     *
     * Recorded because a site issues its cookies to one browser and expects them back from
     * that same browser. Sending them under the app's own identity is what makes a good
     * sign-in look like a stranger holding someone else's cookies.
     */
    private val USER_AGENT_KEY = stringPreferencesKey("cookie_user_agent")

    /** Header yt-dlp expects at the top of a Netscape cookie file. */
    const val FILE_HEADER = "# Netscape HTTP Cookie File\n" +
            "# Generated by Hazel\n" +
            "# This is a generated file. Do not edit."

    // ── Master switch ──

    fun getUseCookies(context: Context): Flow<Boolean> =
        context.dataStore.data.map { prefs -> prefs[USE_COOKIES_KEY] ?: false }

    suspend fun setUseCookies(context: Context, enabled: Boolean) {
        var updatedEntries: List<CookieEntry> = emptyList()
        context.dataStore.edit { prefs ->
            prefs[USE_COOKIES_KEY] = enabled
            val existing = decode(prefs[COOKIES_KEY])
            if (existing.isNotEmpty()) {
                val updated = existing.map { it.copy(enabled = enabled) }
                prefs[COOKIES_KEY] = encode(updated)
                updatedEntries = updated
            }
        }
        writeCookieFile(context, explicitEntries = updatedEntries, explicitUseCookies = enabled)
        InfoCache.clear()
    }

    // ── Entries ──

    fun getEntries(context: Context): Flow<List<CookieEntry>> =
        context.dataStore.data.map { prefs -> decode(prefs[COOKIES_KEY]) }

    /**
     * Adds an entry, or replaces the one that already covers the same site and title.
     * Signing in again to refresh an expired set therefore updates in place rather than
     * leaving two entries behind.
     */
    suspend fun upsert(context: Context, entry: CookieEntry) {
        var updatedEntries: List<CookieEntry> = emptyList()
        var updatedUseCookies: Boolean = true
        context.dataStore.edit { prefs ->
            val existing = decode(prefs[COOKIES_KEY])
            val match = existing.indexOfFirst {
                it.id == entry.id || (it.url == entry.url && it.title == entry.title)
            }
            val updated = if (match >= 0) {
                existing.toMutableList().apply { this[match] = entry.copy(id = existing[match].id) }
            } else {
                existing + entry
            }
            prefs[COOKIES_KEY] = encode(updated)
            if (entry.enabled) {
                prefs[USE_COOKIES_KEY] = true
            }
            updatedEntries = updated
            updatedUseCookies = prefs[USE_COOKIES_KEY] ?: true
        }
        writeCookieFile(context, explicitEntries = updatedEntries, explicitUseCookies = updatedUseCookies)
        InfoCache.clear()
    }

    suspend fun setEnabled(context: Context, id: Long, enabled: Boolean) {
        var updatedEntries: List<CookieEntry> = emptyList()
        var currentUseCookies = false
        context.dataStore.edit { prefs ->
            val existing = decode(prefs[COOKIES_KEY])
            val updated = existing.map {
                if (it.id == id) it.copy(enabled = enabled) else it
            }
            prefs[COOKIES_KEY] = encode(updated)
            if (enabled) {
                prefs[USE_COOKIES_KEY] = true
            }
            currentUseCookies = prefs[USE_COOKIES_KEY] ?: false
            updatedEntries = updated
        }
        writeCookieFile(context, explicitEntries = updatedEntries, explicitUseCookies = currentUseCookies)
        InfoCache.clear()
    }

    suspend fun delete(context: Context, id: Long) {
        var remainingEntries: List<CookieEntry> = emptyList()
        var remainingUseCookies: Boolean = false
        var deletedSite: String? = null
        context.dataStore.edit { prefs ->
            val existing = decode(prefs[COOKIES_KEY])
            val deleted = existing.find { it.id == id }
            if (deleted != null) {
                val site = siteKeyOf(hostOf(deleted.url))
                if (site != null) {
                    deletedSite = site
                } else {
                    val firstDomain = deleted.content.lineSequence()
                        .map { it.substringBefore('\t').trim().removePrefix(".") }
                        .firstOrNull { it.isNotBlank() }
                    deletedSite = firstDomain?.let { siteKeyOf(it) ?: it }
                }
            }
            val remaining = existing.filter { it.id != id }
            prefs[COOKIES_KEY] = encode(remaining)
            if (remaining.isEmpty()) {
                prefs[USE_COOKIES_KEY] = false
            }
            remainingEntries = remaining
            remainingUseCookies = prefs[USE_COOKIES_KEY] ?: false
        }
        withContext(Dispatchers.IO) {
            deletedSite?.let { site ->
                runCatching { File(context.cacheDir, "cookies-$site.txt").delete() }
            }
        }
        writeCookieFile(context, explicitEntries = remainingEntries, explicitUseCookies = remainingUseCookies)
        InfoCache.clear()
    }

    suspend fun deleteAll(context: Context) {
        context.dataStore.edit { prefs ->
            prefs[COOKIES_KEY] = encode(emptyList())
            prefs[USE_COOKIES_KEY] = false
        }
        withContext(Dispatchers.IO) {
            context.cacheDir.listFiles { _, name -> name.startsWith("cookies") }?.forEach {
                runCatching { it.delete() }
            }
        }
        writeCookieFile(context, explicitEntries = emptyList(), explicitUseCookies = false)
        InfoCache.clear()
    }

    // ── The file yt-dlp reads ──

    /** Private to the app; cookies never reach public storage. */
    fun cookieFile(context: Context): File = File(context.cacheDir, "cookies.txt")

    /**
     * Rewrites the cookie file from the entries that are currently switched on.
     *
     * Called after every change so the file can never describe a state the list does not.
     * When cookies are off, or nothing is enabled, the file is emptied rather than deleted,
     * which keeps a stale set from being picked up later.
     */
    suspend fun writeCookieFile(
        context: Context,
        explicitEntries: List<CookieEntry>? = null,
        explicitUseCookies: Boolean? = null
    ) = withContext(Dispatchers.IO) {
        val useCookies = explicitUseCookies ?: getUseCookies(context).first()
        val enabled = if (useCookies) {
            val list = explicitEntries ?: getEntries(context).first()
            list.filter { it.enabled && it.content.isNotBlank() }
        } else {
            emptyList()
        }

        val file = cookieFile(context)
        if (enabled.isEmpty()) {
            runCatching { file.writeText("") }
            return@withContext
        }

        val text = buildString {
            append(FILE_HEADER)
            append('\n')
            enabled.forEach { entry ->
                entry.content.lineSequence().forEach { line ->
                    // Per-entry headers and comments are dropped: one header for the file.
                    if (line.isNotBlank() && !line.startsWith("#")) {
                        append(line)
                        append('\n')
                    }
                }
            }
        }
        runCatching { file.writeText(text) }
    }

    /**
     * The cookie file to hand yt-dlp, or null when cookies are off or none are stored.
     * The file is rewritten first so a change made while a fetch was queued still applies.
     */
    suspend fun activeCookieFile(context: Context): File? {
        if (!getUseCookies(context).first()) return null
        writeCookieFile(context)
        val file = cookieFile(context)
        return file.takeIf { it.exists() && it.length() > 0 }
    }

    /** Records the browser identity a sign-in was collected under. */
    suspend fun setUserAgent(context: Context, userAgent: String) {
        context.dataStore.edit { prefs -> prefs[USER_AGENT_KEY] = userAgent }
    }

    fun getUserAgent(context: Context): Flow<String> =
        context.dataStore.data.map { prefs -> prefs[USER_AGENT_KEY].orEmpty() }

    /**
     * The sign-in to send with a fetch of [url], or [SiteAccess.NONE] when nothing saved
     * covers that site.
     *
     * Cookies are scoped to the site they were collected on. One file holding every sign-in
     * would hand a video site's account cookies to a photo site's servers, which is both a
     * thing the user never agreed to and a way of making a request look stranger than an
     * anonymous one. A link to a site with no saved sign-in is fetched without any.
     *
     * The single place the rest of the app asks, so a read and the download that follows it
     * are made under the same identity.
     */
    suspend fun accessFor(context: Context, url: String): SiteAccess {
        if (!getUseCookies(context).first()) return SiteAccess.NONE

        val site = siteKeyOf(hostOf(url)) ?: return SiteAccess.NONE
        val entries = getEntries(context).first()
            .filter { it.enabled && it.content.isNotBlank() && covers(it, site) }
        if (entries.isEmpty()) return SiteAccess.NONE

        val file = writeSiteFile(context, site, entries) ?: return SiteAccess.NONE
        return SiteAccess(cookieFile = file, userAgent = getUserAgent(context).first())
    }

    /** Whether a saved sign-in belongs to [site]. */
    private fun covers(entry: CookieEntry, site: String): Boolean {
        siteKeyOf(hostOf(entry.url))?.let { return it == site }

        // An imported set names no site, so its own cookies are asked instead. The domain
        // is the first field of a Netscape line.
        return entry.content.lineSequence().any { line ->
            val domain = line.substringBefore('\t').trim().removePrefix(".")
            domain.isNotBlank() && siteKeyOf(domain) == site
        }
    }

    /** The cookie file for one site, written fresh so it always matches the saved list. */
    private suspend fun writeSiteFile(
        context: Context,
        site: String,
        entries: List<CookieEntry>
    ): File? = withContext(Dispatchers.IO) {
        val body = buildString {
            append(FILE_HEADER)
            append('\n')
            entries.forEach { entry ->
                entry.content.lineSequence().forEach { line ->
                    if (line.isNotBlank() && !line.startsWith("#")) {
                        append(line)
                        append('\n')
                    }
                }
            }
        }

        val file = File(context.cacheDir, "cookies-$site.txt")
        runCatching { file.writeText(body) }.getOrNull() ?: return@withContext null
        file.takeIf { it.length() > 0 }
    }

    /**
     * What counts as the same site.
     *
     * The registrable domain, with the short forms a site publishes for itself folded into
     * the name they belong to. Without that, a shortened link looks like a different site
     * from the one the user signed in to and is fetched as a stranger.
     */
    private fun siteKeyOf(url: String): String? {
        val host = url.takeIf { it.isNotBlank() } ?: return null
        SITE_ALIASES[host]?.let { return it }

        val registrable = host.split('.').takeLast(2).joinToString(".")
        return SITE_ALIASES[registrable] ?: registrable.takeIf { it.contains('.') }
    }

    private fun hostOf(value: String): String {
        if (value.isBlank()) return ""
        val withScheme = if ("://" in value) value else "https://$value"
        return runCatching { java.net.URI(withScheme).host.orEmpty() }
            .getOrDefault("")
            .lowercase()
            .removePrefix("www.")
    }

    /** Short forms and sister domains, mapped to the site they are part of. */
    private val SITE_ALIASES = mapOf(
        "youtu.be" to "youtube.com",
        "youtube-nocookie.com" to "youtube.com",
        "google.com" to "youtube.com",
        "instagr.am" to "instagram.com",
        "x.com" to "twitter.com",
        "fb.watch" to "facebook.com",
        "fb.com" to "facebook.com",
        "vm.tiktok.com" to "tiktok.com",
        "vt.tiktok.com" to "tiktok.com"
    )

    /** Whole cookie file as text, for copying out. */
    suspend fun exportText(context: Context): String = withContext(Dispatchers.IO) {
        writeCookieFile(context)
        runCatching { cookieFile(context).readText() }.getOrDefault("")
    }

    /**
     * Takes cookie text the user copied from elsewhere and stores it as a new entry.
     * Anything that is not a Netscape cookie file is rejected rather than saved as junk.
     */
    suspend fun importText(context: Context, text: String, title: String): Boolean {
        val lines = text.lineSequence()
            .map { it.trim() }
            .filter { it.isNotBlank() && !it.startsWith("#") }
            .toList()
        if (lines.isEmpty()) return false

        // Group cookie lines by recognized site (from 1st column of Netscape line)
        val siteToLines = mutableMapOf<String, MutableList<String>>()
        val unmatchedLines = mutableListOf<String>()

        for (line in lines) {
            val parts = line.split('\t')
            val rawDomain = parts.firstOrNull()?.trim()?.removePrefix(".")
            val site = rawDomain?.let { siteKeyOf(it) ?: it }
            if (!site.isNullOrBlank()) {
                siteToLines.getOrPut(site) { mutableListOf() }.add(line)
            } else {
                unmatchedLines.add(line)
            }
        }

        if (siteToLines.isEmpty()) {
            upsert(
                context,
                CookieEntry(
                    id = System.currentTimeMillis(),
                    url = "",
                    title = title,
                    content = lines.joinToString("\n"),
                    enabled = true
                )
            )
            return true
        }

        if (siteToLines.size == 1) {
            val (site, siteLines) = siteToLines.entries.first()
            val allSiteLines = siteLines + unmatchedLines
            val url = if (site.contains(".")) "https://www.$site" else ""
            upsert(
                context,
                CookieEntry(
                    id = System.currentTimeMillis(),
                    url = url,
                    title = title,
                    content = allSiteLines.joinToString("\n"),
                    enabled = true
                )
            )
        } else {
            var offset = 0L
            for ((site, siteLines) in siteToLines) {
                val url = if (site.contains(".")) "https://www.$site" else ""
                val entryTitle = if (title.isNotBlank()) "$title ($site)" else site
                upsert(
                    context,
                    CookieEntry(
                        id = System.currentTimeMillis() + offset++,
                        url = url,
                        title = entryTitle,
                        content = siteLines.joinToString("\n"),
                        enabled = true
                    )
                )
            }
            if (unmatchedLines.isNotEmpty()) {
                upsert(
                    context,
                    CookieEntry(
                        id = System.currentTimeMillis() + offset,
                        url = "",
                        title = title,
                        content = unmatchedLines.joinToString("\n"),
                        enabled = true
                    )
                )
            }
        }
        return true
    }

    // ── JSON ──

    private fun encode(entries: List<CookieEntry>): String {
        val array = JSONArray()
        entries.forEach { entry ->
            array.put(
                JSONObject().apply {
                    put("id", entry.id)
                    put("url", entry.url)
                    put("title", entry.title)
                    put("content", entry.content)
                    put("enabled", entry.enabled)
                }
            )
        }
        return array.toString()
    }

    private fun decode(raw: String?): List<CookieEntry> {
        if (raw.isNullOrBlank()) return emptyList()
        return runCatching {
            val array = JSONArray(raw)
            (0 until array.length()).mapNotNull { index ->
                array.optJSONObject(index)?.let { json ->
                    CookieEntry(
                        id = json.optLong("id"),
                        url = json.optString("url"),
                        title = json.optString("title"),
                        content = json.optString("content"),
                        enabled = json.optBoolean("enabled", true)
                    )
                }
            }
        }.getOrDefault(emptyList())
    }
}
